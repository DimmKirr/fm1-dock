#!/usr/bin/env python3
"""FM-1 SID's 8x12 bitmap font (DejaVu Sans Mono at 11 px, ASCII 32..126, one byte a row, MSB
left), as its firmware/gen_assets.py makes it, into modules/sid/fm1sid_font.h:
    DEJAVU_MONO=.../DejaVuSansMono.ttf modules/sid/gen_font.py
SPDX-License-Identifier: BSD-2-Clause"""
import os
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

f = ImageFont.truetype(os.environ.get("DEJAVU_MONO", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"), 11)
rows = []
for c in range(32, 127):
    im = Image.new("1", (8, 12), 0)
    ImageDraw.Draw(im).text((0, -1), chr(c), font=f, fill=1)
    for y in range(12):
        b = 0
        for x in range(8):
            b |= im.getpixel((x, y)) << (7 - x)
        rows.append(b)
out = Path(__file__).with_name("fm1sid_font.h")
lines = [",".join(str(b) for b in rows[i:i + 24]) for i in range(0, len(rows), 24)]
out.write_text("/* generated by modules/sid/gen_font.py (DejaVu Sans Mono: Bitstream Vera licence) */\n"
               "static const uint8_t FONT[95 * 12] = {\n" + ",\n".join(lines) + "};\n")
print(out, len(rows))
